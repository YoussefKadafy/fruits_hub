class AddressEntity {
  final String name;
  final String phone;
  final String address;
  final String city;
  final String  neighborhood;
  final String apartment;
  final String floor;
  final String buildingNumber;
  AddressEntity({
    required this.name,
    required this.phone,
    required this.address,
    required this.city,
    required this.neighborhood,
    required this.apartment,
    required this.floor,
    required this.buildingNumber,
  });
}